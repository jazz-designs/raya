export const getCollectionsWithMeta = (): CollectionItem[] => {
  return COLLECTIONS.map(col => {
    const items = products.filter(p => p.category === col.category);
    const minPrice = items.length > 0 ? Math.min(...items.map(p => p.price)) : col.startingPrice;
    return {
      ...col,
      itemCount: items.length,
      startingPrice: minPrice,
    };
  });
};

